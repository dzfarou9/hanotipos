/// إعدادات تسجيل الدخول عبر رمز QR.
///
/// ملاحظة أمان (C-1): `appEncryptionKey` مضمّن في التطبيق ومشارك بين كل
/// نسخه، فهو إخفاء (obfuscation) وليس حماية كاملة. ملح كل حساب يجعل مفتاح
/// التشفير مختلفاً لكل حساب (الإصدار 4 من الصيغة)، لكن من يفكّك APK يستطيع
/// استخراج السر الأساسي وقراءة الملح من الرمز نفسه — لذلك قُصّرت مدة
/// الصلاحية إلى 45 ثانية ويُجدَّد الرمز تلقائياً كل 30 ثانية لتقليص حجم
/// الضرر عند تسرّب صورة الرمز.
///
// TODO(C-1): التصميم المستهدف (يحتاج Cloud Functions + باك-إند منشور):
//   1) جهاز العرض يطلب من الخادم رمز دخول لمرة واحدة (nonce/token قصير
//      العمر) مرتبطاً بالحساب، والخادم يخزّنه بحالة "غير مستخدم".
//   2) الرمز الذي يُطبع في QR يحتوي التوكن فقط — لا كلمة المرور أبداً،
//      فلا يوجد سرّ قابل للسرقة داخل APK ولا داخل الصورة.
//   3) جهاز المسح يرسل التوكن إلى الخادم الذي يتحقق من الصلاحية والاستخدام
//      الأوحد (single-use) ثم يُنشئ جلسة (Firebase custom token) للجهاز.
//   4) إلغاء صلاحية التوكنات يتم في الخادم، فلا اعتماد على ساعة الجهاز.
//   حتى ذلك الحين تبقى الإجراءات الحالية (ملح لكل حساب + صلاحية 45 ثانية
//   + تجديد كل 30 ثانية + رفض الإصدارات القديمة) حلاً مؤقتاً.
class QrLoginConfig {
  QrLoginConfig._();

  // ⭐ السر الأساسي (32 بايت UTF-8) — يُخلط مع ملح الحساب عبر SHA-256
  // لإنتاج مفتاح AES مختلف لكل حساب/تثبيت.
  static const String appEncryptionKey = 'HanotiPOS-QR-Login-Key-2026-ABCD';

  // ⭐ مدة صلاحية رمز QR (خُفّضت من 90 إلى 45 ثانية لتقليص نافذة السرقة)
  static const Duration qrValidity = Duration(seconds: 45);

  // ⭐ إعادة توليد الرمز تلقائياً أثناء فتح النافذة (IV جديد + انتهاء جديد)
  static const Duration qrRefreshInterval = Duration(seconds: 30);

  // ⭐ أقصى فرق مقبول في الساعة بين جهاز العرض وجهاز المسح
  static const Duration maxClockSkew = Duration(seconds: 10);

  // ⭐ رفض الرموز ذات تاريخ الانتهاء البعيد في المستقبل (حماية من العبث
  //    بحمولة الإصدار القديم أو تمديد صلاحية ملفّق)
  static const Duration maxFutureSkew = Duration(seconds: 120);
}
